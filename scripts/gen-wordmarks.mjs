// Generates src/components/portfolio/home/metal-marks/wordmarks.ts: the simple-icons glyph plus the
// product name set in Geist Regular, converted to outlines (technology wall, EF-06…EF-08).
//
// fontkit is not a dependency of the site; install it only to run this script:
//   npm install --no-save fontkit@2.0.4
//   node scripts/gen-wordmarks.mjs
//   npx prettier --write src/components/portfolio/home/metal-marks/wordmarks.ts
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const requireCjs = createRequire(import.meta.url);
const fontkit = requireCjs('fontkit');
const REPO = fileURLToPath(new URL('..', import.meta.url)).replace(/\/$/, '');
const icons = await import('simple-icons');
const font = fontkit.openSync(`${REPO}/node_modules/geist/dist/fonts/geist-sans/Geist-Regular.ttf`);

const SIZE = 100; // font size in viewBox units
const TRACKING = -0.02; // em
const ICON_TO_CAP = 1.36; // icon height relative to the cap height
const GAP_TO_CAP = 0.36; // gap between icon and name, relative to the cap height

const WORDMARKS = [
  ['react', 'siReact', 'React'],
  ['typescript', 'siTypescript', 'TypeScript'],
  ['payloadcms', 'siPayloadcms', 'Payload'],
  ['prisma', 'siPrisma', 'Prisma'],
  ['vitest', 'siVitest', 'Vitest'],
];

const s = SIZE / font.unitsPerEm;
const cap = font.capHeight * s;
const iconSize = cap * ICON_TO_CAP;
const baseline = (iconSize + cap) / 2; // cap band centred on the icon
const r = (n) => Math.round(n * 100) / 100;

const out = {};
for (const [id, key, text] of WORDMARKS) {
  const icon = icons[key];
  if (!icon || icon.slug !== id) throw new Error(`bad icon ${key}`);
  const run = font.layout(text);
  let x = iconSize + cap * GAP_TO_CAP;
  const parts = [];
  let minY = 0;
  let maxY = iconSize;
  run.glyphs.forEach((g, i) => {
    const pos = run.positions[i];
    const p = g.path.transform(s, 0, 0, -s, x + pos.xOffset * s, baseline - pos.yOffset * s);
    const bb = p.bbox;
    if (Number.isFinite(bb.minY)) {
      minY = Math.min(minY, bb.minY);
      maxY = Math.max(maxY, bb.maxY);
    }
    parts.push(p.toSVG().replace(/(\d+\.\d{3,})/g, (m) => String(r(Number(m)))));
    x += pos.xAdvance * s + (i < run.glyphs.length - 1 ? TRACKING * SIZE : 0);
  });
  const lastBox = run.glyphs.at(-1).path.transform(s, 0, 0, -s, 0, 0).bbox;
  const width = r(x - (run.positions.at(-1).xAdvance * s - lastBox.maxX));
  out[id] = {
    text,
    viewBox: `0 ${r(minY)} ${width} ${r(maxY - minY)}`,
    ratio: r(width / (maxY - minY)),
    icon: { size: r(iconSize), scale: r(iconSize / 24) },
    name: parts.join(''),
  };
}

const header = `// GENERATED by scripts/gen-wordmarks.mjs (Geist Regular 1.9.2 via fontkit, simple-icons 16.36.0): do not edit by hand.
// Wordmarks of the technology wall: the simple-icons glyph (24×24, scaled to \`icon.scale\`) followed by the
// product name converted to outlines, so the DOM fallback and the metal raster share the exact same shape
// without waiting for a webfont. Geist is OFL-1.1 (src/assets/fonts/geist-ofl.txt).
`;
const body = `export interface Wordmark {
  /** Product name the outlines spell (also the accessible name). */
  text: string;
  viewBox: string;
  /** Width / height of the viewBox. */
  ratio: number;
  /** Glyph box: drawn at (0, 0) with \`scale\` applied to the 24×24 simple-icons path. */
  icon: { size: number; scale: number };
  /** Outlines of the name, in viewBox units. */
  name: string;
}

export const WORDMARKS: Readonly<Record<string, Wordmark>> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(
  `${REPO}/src/components/portfolio/home/metal-marks/wordmarks.ts`,
  header + '\n' + body,
);
for (const [k, v] of Object.entries(out)) console.log(k, v.viewBox, v.ratio, v.name.length);
